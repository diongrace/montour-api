create table etablissement (
    id      bigint generated by default as identity primary key,
    nom     varchar(120) not null,
    slug    varchar(80)  not null unique,
    adresse varchar(200)
);

create table service_accueil (
    id                   bigint generated by default as identity primary key,
    etablissement_id     bigint       not null references etablissement (id),
    nom                  varchar(100) not null,
    prefixe              varchar(3)   not null,
    ouvert               boolean      not null default true,
    duree_par_defaut_min integer      not null default 5
);

create table guichet (
    id         bigint generated by default as identity primary key,
    service_id bigint      not null references service_accueil (id),
    nom        varchar(60) not null,
    actif      boolean     not null default true
);

create table utilisateur (
    id                bigint generated by default as identity primary key,
    etablissement_id  bigint       not null references etablissement (id),
    nom               varchar(100) not null,
    email             varchar(150) not null unique,
    mot_de_passe_hash varchar(100) not null,
    role              varchar(20)  not null
);

create table ticket (
    id           bigint generated by default as identity primary key,
    service_id   bigint      not null references service_accueil (id),
    numero       integer     not null,
    code         varchar(10) not null,
    jour         date        not null,
    statut       varchar(20) not null,
    jeton_client uuid        not null unique,
    cree_le      timestamp   not null,
    appele_le    timestamp,
    termine_le   timestamp,
    guichet_id   bigint references guichet (id),
    agent_id     bigint references utilisateur (id),
    constraint uk_ticket_service_jour_numero unique (service_id, jour, numero)
);

create index idx_ticket_file on ticket (service_id, statut, jour);
